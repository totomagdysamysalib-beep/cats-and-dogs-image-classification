"""# Train and test step"""

def train_step(model, dataset, loss_fn, optimizer):
    model.train()

    total_loss = 0
    total_correct = 0
    total_samples = 0

    for x, y in dataset:
        x, y = x.to(device), y.to(device)

        optimizer.zero_grad()

        y_pred = model(x)
        loss = loss_fn(y_pred, y)

        loss.backward()
        optimizer.step()

        batch_size = y.size(0)

        total_loss += loss.item() * batch_size
        total_correct += (y_pred.argmax(dim=1) == y).sum().item()
        total_samples += batch_size

    avg_loss = total_loss / total_samples
    accuracy = total_correct / total_samples

    return avg_loss, accuracy

def test_step(model,dataset,loss_fn):
  model.eval()
  with torch.inference_mode():
    acc,total_loss=0,0
    for x,y in dataset:
      x, y = x.to(device), y.to(device)
      y_pred=model(x)
      loss=loss_fn(y_pred,y)
      total_loss+=loss

      acc+=(y_pred.argmax(dim=1)==y).sum().item()/len(y_pred)
    acc/=len(dataset)
    total_loss/=len(dataset)
  return total_loss,acc

def train(model,train_data,test_data,optimizer,loss_fn,epochs=5):
  results={
      "train loss ":[],
      "train acc ":[],
      "test loss ":[],
      "test acc ":[]
  }
  for epoch in range(epochs):
    train_loss,train_acc=train_step(model,train_data,loss_fn,optimizer)
    test_loss,test_acc=test_step(model,test_data,loss_fn)
    print(
        f"The train loss: {train_loss:.4f} | "
        f"The train accuracy:  {train_acc:.4f} | "
        f"The test loss: {test_loss:.4f} | "
        f"The test accuracy: {test_acc:.4f}"
    )

    results["train loss "].append(train_loss.item() if isinstance(train_loss,torch.Tensor) else train_loss)
    results["train acc "].append(train_acc.item() if isinstance(train_acc,torch.Tensor) else train_acc)
    results["test acc "].append(test_acc.item() if isinstance(test_acc,torch.Tensor) else test_acc)
    results["test loss "].append(test_loss.item() if isinstance(test_loss,torch.Tensor) else test_loss)

  return results

